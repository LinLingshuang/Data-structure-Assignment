/*24. 单链表基本操作-创建插入删除遍历
单链表基本操作-创建插入删除遍历
一、问题描述
实现一个带头结点的单链表，支持以下操作：

CREATE n：创建一个包含n个元素的链表，元素值依次为1到n

INSERT k x：在第k个位置（从1开始）插入元素x

DELETE k：删除第k个位置的元素

PRINT：输出链表所有元素

二、输入形式
第一行输入一个正整数m（1 ≤ m ≤ 1000），表示操作数量。
接下来m行，每行一个操作，格式如上所述。

三、输出形式
对于每个PRINT操作，输出一行，包含链表的所有元素，用空格分隔。如果链表为空，输出"EMPTY"。

四、样例输入

8
CREATE 3
PRINT
INSERT 2 5
PRINT
DELETE 3
PRINT
DELETE 1
PRINT
五、样例输出

1 2 3
1 5 2 3
1 5 3
5 3
六、样例说明
操作过程：

CREATE 3：创建链表[1,2,3]

PRINT：输出1 2 3

INSERT 2 5：在第2位插入5，链表变为[1,5,2,3]

PRINT：输出1 5 2 3

DELETE 3：删除第3位（值为2），链表变为[1,5,3]

PRINT：输出1 5 3

DELETE 1：删除第1位（值为1），链表变为[5,3]

PRINT：输出5 3

七、评分标准
共6个测试用例。

八、类库使用要求
必须手动实现链表结构，禁止使用STL list。可以使用iostream。*/