/*8. 链栈基本操作
链栈基本操作
一、问题描述
实现一个链栈，支持以下操作：
PUSH x：将元素x压入栈顶
POP：弹出栈顶元素，栈空时输出"EMPTY"
TOP：查看栈顶元素，栈空时输出"EMPTY"
IS_EMPTY：输出"YES"或"NO"表示栈是否为空
二、输入形式
第一行输入一个正整数m（1 ≤ m ≤ 100000），表示操作数量。
接下来m行，每行一个操作，格式如上所述。
三、输出形式
对于每个需要输出的操作，输出对应的结果，每行一个。
四、样例输入
6
PUSH 10
PUSH 20
TOP
POP
IS_EMPTY
POP
五、样例输出
20
20
NO
EMPTY
10
六、样例说明
操作过程：
PUSH 10：栈[10]
PUSH 20：栈[20,10]（20在栈顶）
TOP：输出20
POP：弹出20，输出20
IS_EMPTY：栈非空，输出NO
POP：弹出10，栈为空
七、评分标准
共6个测试用例。
八、类库使用要求
必须手动实现链表结构，禁止使用STL stack和list。*/