/*15. 两个有序链表合并
两个有序链表合并
一、问题描述
将两个升序链表合并为一个新的升序链表。新链表是通过拼接给定的两个链表的所有节点组成的。

二、输入形式
两行输入，每行表示一个链表，节点值以空格分隔，以-1结束。

三、输出形式
输出合并后的有序链表节点值，用空格分隔。

四、样例输入

1 2 4 -1
1 3 4 -1
五、样例输出

1 1 2 3 4 4
六、样例说明
链表1：1 → 2 → 4
链表2：1 → 3 → 4
合并后：1 → 1 → 2 → 3 → 4 → 4

七、评分标准
共6个测试用例。

八、类库使用要求
必须手动实现链表结构。可以使用iostream。*/